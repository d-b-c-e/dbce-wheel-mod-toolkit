using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using Dbce.Wheel.Ffb;
using Xunit;

namespace Dbce.Wheel.Ffb.Tests
{
    /// <summary>
    /// Checks the toolkit's force model against art of rally's shipped curve.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <c>profiles/force-profiles.ini</c> claims <c>simlite@1</c> is art of rally's
    /// 0.2.2 tuning, and until this test nothing enforced it. That claim failing
    /// is silent: a subtly wrong force does not throw, it feels like the mod got
    /// worse some months after whatever changed.
    /// </para>
    /// <para>
    /// The vector under <c>data/</c> was generated by that repo's own
    /// <c>tools/force-vector</c>, which links its shipping <c>ForceCurve.cs</c>
    /// rather than copying it, so it is what the game does rather than what
    /// someone believed it does.
    /// </para>
    /// <para>
    /// Two conventions differ and are handled explicitly rather than hidden.
    /// Sign: this model returns a <b>negative</b> force for a positive lateral
    /// load, because positive means "toward positive steer" and centring is the
    /// opposite; art of rally's curve is unsigned in that sense. Clamping order
    /// agreed as of 0.7.0: see
    /// <see cref="ModelReturnsPastFullScaleAndTheShaperBoundsIt"/>.
    /// </para>
    /// </remarks>
    public class SimLiteVectorTests
    {
        private const float FyReference = 11500f;
        private const float IdealDeg = 8.5f;

        public sealed class Row
        {
            public float Fy, SlipDeg, IdealDeg, SpeedKmh, Trail, Normalised;
            public int Device;
        }

        private static string VectorPath()
        {
            var dir = new DirectoryInfo(AppContext.BaseDirectory);
            while (dir != null)
            {
                var p = Path.Combine(dir.FullName, "data", "art-of-rally-0.2.2-force-curve.csv");
                if (File.Exists(p)) return p;
                dir = dir.Parent;
            }
            return null;
        }

        private static List<Row> Grid()
        {
            var path = VectorPath();
            Assert.True(path != null, "data/art-of-rally-0.2.2-force-curve.csv not found");
            var rows = new List<Row>();
            foreach (var raw in File.ReadAllLines(path))
            {
                var line = raw.Trim();
                if (line.Length == 0) break;                 // the grid ends at the blank line
                if (line.StartsWith("#") || line.StartsWith("fy_total_n")) continue;
                var f = line.Split(',');
                if (f.Length != 7) continue;
                rows.Add(new Row
                {
                    Fy = P(f[0]), SlipDeg = P(f[1]), IdealDeg = P(f[2]), SpeedKmh = P(f[3]),
                    Trail = P(f[4]), Normalised = P(f[5]), Device = (int)P(f[6]),
                });
            }
            return rows;
        }

        private static float P(string s) => float.Parse(s, NumberStyles.Float, CultureInfo.InvariantCulture);

        private static ForceProfile SimLite()
        {
            var dir = new DirectoryInfo(AppContext.BaseDirectory);
            while (dir != null && !File.Exists(Path.Combine(dir.FullName, "profiles", "force-profiles.ini")))
                dir = dir.Parent;
            Assert.True(dir != null, "profiles/force-profiles.ini not found");
            return ForceProfile.Load(Path.Combine(dir.FullName, "profiles", "force-profiles.ini"), "simlite@1");
        }

        private static ForceInputs InputsFor(Row r) => new ForceInputs
        {
            FrontLateralForce = r.Fy,
            HasFrontLateralForce = true,
            FrontSlipAngleDeg = r.SlipDeg,
            IdealSlipAngleDeg = r.IdealDeg,
            HasSlip = true,
            SpeedMps = r.SpeedKmh / 3.6f,
        };

        [Fact]
        public void TheVectorLoadsAndCoversTheInterestingCases()
        {
            var g = Grid();
            Assert.True(g.Count > 500, "expected the full grid, got " + g.Count);
            Assert.Contains(g, r => r.Fy < 0);                                  // both directions
            Assert.Contains(g, r => Math.Abs(r.Normalised) >= 1f);              // saturation
            Assert.Contains(g, r => r.SpeedKmh > 3 && r.SpeedKmh < 12);         // mid-fade
            Assert.Contains(g, r => r.SlipDeg > 2 * r.IdealDeg);                // past the trail floor
        }

        [Fact]
        public void TrailMatchesExactly()
        {
            // 1.0 falling linearly to TrailFloor at TrailSlipSpan x ideal, then held.
            var s = SimLite().Model;
            foreach (var r in Grid())
            {
                float t = Math.Min(1f, r.SlipDeg / (s.TrailSlipSpan * r.IdealDeg));
                float mine = 1f - (1f - s.TrailFloor) * t;
                Assert.True(Math.Abs(mine - r.Trail) < 1e-5f,
                    $"trail at slip {r.SlipDeg} of ideal {r.IdealDeg}: mine {mine}, theirs {r.Trail}");
            }
        }

        [Fact]
        public void ModelReproducesTheUnfadedForce()
        {
            // The model's own output, before any speed fade: fy x trail / reference,
            // negated for this repo's sign convention, and NOT bounded - the model
            // reports a force past full scale rather than hiding it, which is what
            // lets the fade and the soft saturation do their jobs. Their vector's
            // own column is clamped because they clamp last; FullCurveMatches is
            // where the two are compared after that bound is applied.
            var p = SimLite();
            foreach (var r in Grid().Where(r => r.SpeedKmh >= 12))     // fade fully open
            {
                var model = new ForceModel(p.Model);
                float mine = model.Compute(InputsFor(r), 1f / 60f);
                float theirs = r.Fy * r.Trail / FyReference;
                Assert.True(Math.Abs(mine - -theirs) < 1e-4f,
                    $"fy {r.Fy} slip {r.SlipDeg}: mine {mine}, theirs(negated) {-theirs}");
            }
        }

        [Fact]
        public void FadeMatchesTheirSmoothStep()
        {
            // Unity's SmoothStep, cubic 3t^2-2t^3 on a clamped t - not a linear ramp.
            var p = SimLite();
            foreach (var speed in Grid().Select(r => r.SpeedKmh).Distinct())
            {
                float t = Math.Max(0f, Math.Min(1f, (speed - p.Shaper.FadeStartKmh) /
                                                    (p.Shaper.FadeFullKmh - p.Shaper.FadeStartKmh)));
                float mine = t * t * (3f - 2f * t);

                // Recover their fade from a row the model does not saturate.
                var row = Grid().First(r => r.SpeedKmh == speed && r.Fy == 500 && r.SlipDeg == 0);
                float unfaded = row.Fy * row.Trail / FyReference;
                float theirs = unfaded == 0f ? mine : row.Normalised / unfaded;
                Assert.True(Math.Abs(mine - theirs) < 1e-4f,
                    $"fade at {speed} km/h: mine {mine}, theirs {theirs}");
            }
        }

        /// <summary>
        /// The fade is a SHAPE, not two numbers, and a refactor can linearise it
        /// silently: both curves agree at the endpoints and at the midpoint, so
        /// only the quarter points tell them apart.
        /// </summary>
        [Fact]
        public void FadeIsCubicAndWouldFailIfLinearised()
        {
            var p = SimLite();
            float a = p.Shaper.FadeStartKmh, b = p.Shaper.FadeFullKmh;
            var shaper = CurveOnlyShaper(p);

            // A force well inside full scale, so only the fade is being measured.
            const float Fy = 500f;
            float unfaded = Fy / FyReference;

            foreach (float frac in new[] { 0f, 0.25f, 0.5f, 0.75f, 1f })
            {
                float kmh = a + frac * (b - a);
                var model = new ForceModel(p.Model);
                var inputs = new ForceInputs
                {
                    FrontLateralForce = Fy, HasFrontLateralForce = true,
                    FrontSlipAngleDeg = 0f, IdealSlipAngleDeg = IdealDeg, HasSlip = true,
                    SpeedMps = kmh / 3.6f,
                };
                float mine = Math.Abs(shaper.Shape(model.Compute(inputs, 1f / 60f), kmh, 1f / 60f));
                float cubic = frac * frac * (3f - 2f * frac);
                Assert.True(Math.Abs(mine - unfaded * cubic) < 1e-4f,
                    $"fade at {frac:P0} of the band: mine {mine}, cubic {unfaded * cubic}");

                // At the quarter points a linear ramp gives a different answer, so
                // this assertion is what actually catches a linearisation.
                if (frac == 0.25f || frac == 0.75f)
                    Assert.True(Math.Abs(unfaded * cubic - unfaded * frac) > 1e-3f,
                        "the cubic and linear fades are indistinguishable here, so this test proves nothing");
            }
        }

        /// <summary>
        /// The whole chain, on every row - saturating ones included, since the
        /// clamp moved to the device edge and the two pipelines now agree there.
        /// </summary>
        [Fact]
        public void FullCurveMatches()
        {
            var p = SimLite();
            int checked_ = 0, saturating = 0;
            foreach (var r in Grid())
            {
                if (Math.Abs(r.Fy * r.Trail / FyReference) > 1f) saturating++;

                var model = new ForceModel(p.Model);
                var shaper = CurveOnlyShaper(p);
                float mine = shaper.Shape(model.Compute(InputsFor(r), 1f / 60f), r.SpeedKmh, 1f / 60f);

                Assert.True(Math.Abs(mine - -r.Normalised) < 1e-4f,
                    $"fy {r.Fy} slip {r.SlipDeg} speed {r.SpeedKmh}: mine {mine}, theirs(negated) {-r.Normalised}");

                // And the integer the wheel actually receives. A cast truncates
                // toward zero, which is what their device column does too.
                Assert.Equal(-r.Device, (int)(mine * 10000f));
                checked_++;
            }
            Assert.Equal(Grid().Count, checked_);
            Assert.True(saturating > 0,
                "no row saturates, so this test no longer proves the clamp is at the edge");
        }

        /// <summary>
        /// The clamp is a device limit and lives at the device edge, not in the
        /// model. This is what that buys, and it is asserted so a well-meaning
        /// refactor cannot put the bound back.
        /// </summary>
        /// <remarks>
        /// Until 0.7.0 <c>ForceModel.Compute</c> clamped to +-1 before returning,
        /// so the shaper's fade scaled an already-clamped value and its soft
        /// saturation had nothing left to compress: every force from full scale
        /// upward arrived as exactly 1.0. Art of rally fades first and clamps
        /// last, its vector says so, and the two now agree on every row.
        /// </remarks>
        [Fact]
        public void ModelReturnsPastFullScaleAndTheShaperBoundsIt()
        {
            var p = SimLite();
            var model = new ForceModel(p.Model);

            // Three times the reference force. The model must report it, not hide it.
            var big = new ForceInputs
            {
                FrontLateralForce = 3f * FyReference, HasFrontLateralForce = true,
                FrontSlipAngleDeg = 0f, IdealSlipAngleDeg = IdealDeg, HasSlip = true,
                SpeedMps = 100f / 3.6f,
            };
            float raw = model.Compute(big, 1f / 60f);
            Assert.True(Math.Abs(raw) > 2.5f,
                "the model clamped: a force past full scale is information the fade and the " +
                "soft saturation need, and bounding it here throws that away. Got " + raw);

            // The shaper is where the device limit lives, and it must hold.
            var shaper = CurveOnlyShaper(p);
            float shaped = shaper.Shape(raw, 100f, 1f / 60f);
            Assert.True(Math.Abs(shaped) <= p.Shaper.PeakLimit + 1e-6f,
                "the shaper let " + shaped + " through; the device edge is the one bound that must hold");
        }

        /// <summary>
        /// The reason the change was worth making, in one number: soft saturation
        /// only does its job on an unclamped input.
        /// </summary>
        [Fact]
        public void SoftSaturationCanNowDistinguishForcesPastFullScale()
        {
            // arcade-outrun@1 asks for tanh; before the change every force at or
            // above full scale reached it as exactly 1.0, so a crash felt the same
            // as a hard corner.
            ForceShaper Tanh() => new ForceShaper
            {
                Strength = 50, SoftSaturation = 1f, Deadzone = 0f, OutputDeadband = 0f,
                AttackSmoothing = 0f, DecaySmoothing = 0f, SlewPerSecond = 0f,
                RampSeconds = 0f, FadeStartKmh = 0f, FadeFullKmh = 0f,
            };
            float atFullScale = Tanh().Shape(1.0f, 100f, 1f / 60f);
            float wellPast = Tanh().Shape(2.0f, 100f, 1f / 60f);
            Assert.True(wellPast - atFullScale > 0.15f,
                $"a force of 2.0 should still be felt as stronger than 1.0; got {atFullScale} and {wellPast}");
        }

        /// <summary>
        /// A shaper carrying only the parts the vector describes: the speed fade,
        /// the gain and the final clamp. Deadzone, smoothing, slew, ramp and output
        /// deadband are conditioning the vector deliberately excludes, and
        /// <see cref="SimLiteShaperSettingsAreNotArtOfRallys"/> is where those are
        /// held to account.
        /// </summary>
        private static ForceShaper CurveOnlyShaper(ForceProfile p) => new ForceShaper
        {
            Strength = p.Shaper.Strength,
            Invert = p.Shaper.Invert,
            FadeStartKmh = p.Shaper.FadeStartKmh,
            FadeFullKmh = p.Shaper.FadeFullKmh,
            PeakLimit = p.Shaper.PeakLimit,
            Deadzone = 0f, AttackSmoothing = 0f, DecaySmoothing = 0f,
            SlewPerSecond = 0f, OutputDeadband = 0f, RampSeconds = 0f,
            SoftSaturation = 0f,
        };

        /// <summary>
        /// The half of the claim that was wrong. simlite@1's model settings are art
        /// of rally's; its shaper settings were this repo's defaults, which the
        /// vector shows the game does not use. simlite@2 corrects it.
        /// </summary>
        [Fact]
        public void SimLiteShaperSettingsAreNotArtOfRallys()
        {
            var one = SimLite().Shaper;
            // Recorded so the mistake is visible rather than quietly fixed: these
            // came from ForceShaper's defaults, not from the game.
            Assert.True(one.Deadzone > 0f || one.RampSeconds > 0f || one.OutputDeadband > 0f,
                "simlite@1 no longer carries the wrong shaper defaults - update this test and the note in the profile");

            var dir = new DirectoryInfo(AppContext.BaseDirectory);
            while (dir != null && !File.Exists(Path.Combine(dir.FullName, "profiles", "force-profiles.ini")))
                dir = dir.Parent;
            var two = ForceProfile.Load(Path.Combine(dir.FullName, "profiles", "force-profiles.ini"), "simlite@2");

            // What the vector actually evidences.
            Assert.Equal(0f, two.Shaper.Deadzone);
            Assert.Equal(0f, two.Shaper.OutputDeadband);
            Assert.Equal(0f, two.Shaper.RampSeconds);
            Assert.Equal(0f, two.Shaper.SlewPerSecond);
            Assert.Equal(0f, two.Shaper.SoftSaturation);
            Assert.Equal(3f, two.Shaper.FadeStartKmh);
            Assert.Equal(12f, two.Shaper.FadeFullKmh);
            Assert.Equal(50, two.Shaper.Strength);
            // Their smoothing is one symmetric coefficient, shipped at 0.2, so
            // attack and decay must be equal for the two to be able to agree.
            Assert.Equal(0.2f, two.Shaper.AttackSmoothing);
            Assert.Equal(two.Shaper.AttackSmoothing, two.Shaper.DecaySmoothing);
            // The model half was right all along.
            Assert.Equal(11500f, two.Model.LateralForceReference);
            Assert.Equal(0.6f, two.Model.TrailFloor);
            Assert.Equal(2f, two.Model.TrailSlipSpan);
        }

        /// <summary>
        /// Their smoothing is a symmetric first-order lerp. Ours is the same shape
        /// when attack equals decay, which simlite@2 ensures, so the step response
        /// in the vector is reproducible.
        /// </summary>
        [Fact]
        public void SmoothingStepResponseMatchesWhenAttackEqualsDecay()
        {
            var path = VectorPath();
            var lines = File.ReadAllLines(path);
            int start = Array.FindIndex(lines, l => l.StartsWith("smoothing,step"));
            Assert.True(start > 0, "the smoothing block is missing from the vector");

            var byCoefficient = new Dictionary<float, List<(int step, float target, float output)>>();
            for (int i = start + 1; i < lines.Length; i++)
            {
                var f = lines[i].Trim().Split(',');
                if (f.Length != 4) continue;
                float k = P(f[0]);
                if (!byCoefficient.ContainsKey(k)) byCoefficient[k] = new List<(int, float, float)>();
                byCoefficient[k].Add(((int)P(f[1]), P(f[2]), P(f[3])));
            }
            Assert.NotEmpty(byCoefficient);

            foreach (var kv in byCoefficient)
            {
                float k = kv.Key;
                var shaper = new ForceShaper
                {
                    Strength = 50, Deadzone = 0f, OutputDeadband = 0f, RampSeconds = 0f,
                    SlewPerSecond = 0f, SoftSaturation = 0f, FadeStartKmh = 0f, FadeFullKmh = 0f,
                    AttackSmoothing = k, DecaySmoothing = k,
                };
                foreach (var (step, target, expected) in kv.Value)
                {
                    float mine = shaper.Shape(target, 1000f, 1f / 60f);
                    Assert.True(Math.Abs(mine - expected) < 1e-4f,
                        $"smoothing {k} step {step}: mine {mine}, theirs {expected}");
                }
            }
        }
    }
}
